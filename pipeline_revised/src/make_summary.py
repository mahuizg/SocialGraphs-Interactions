"""Writes CONCLUSIONS.md from the results files, so every number in it is one the code produced."""
import json

import pandas as pd

from common import RES, ROOT


def J(n):
    return json.loads((RES / n).read_text())


def ci(x, d=2):
    return f"[{x[0]:.{d}f}, {x[1]:.{d}f}]"


r1, r2, r3, s = J("rq1_embeddedness_runs1000.json"), J("rq2_text_perms200.json"), J("rq3_homophily_runs1000.json"), J("selection_check.json")
D, P, P2, M, H = (r1["descriptives_raw"], r1["permutation_field_decade_citation5"], r1["permutation_subfield_decade_citation3"],
                  r1["models_in_degree"], r1["models_in_degree"]["hurdle"])
MO, F, c, w = r1["models_out_degree"], r1["field_by_gender"], r2["classifier_strict_masking"], r2["words"]
nb, g = M["negative_binomial"], s["gap_without_citation_control"]
cx = r3["summary_community_x_decade"]
L = []
A = L.append
A("# Conclusions (revised analysis)\n")
A("*Generated by `src/make_summary.py` from the files in `results/`. Do not edit numbers by hand: re-run the script.*\n")
A("## One sentence\n")
A(f"At equal citations, field and birth decade, women scientists' Wikipedia pages receive about "
  f"{100 * (1 - nb['irr']):.0f}% fewer links from other scientists' pages than men's "
  f"(rate ratio {nb['irr']:.2f}, 95% CI {ci(nb['ci95'])}), give fewer links themselves, and are more often "
  f"cut off from the network altogether; their text is also recognisably different even with names and gender words hidden.\n")
A("The claim is **less embedded**, not *less visible*: we measure links between scientists' pages, not readers.\n")

A("## RQ1. Embeddedness at equal impact\n")
A(f"Comparison set: {r1['comparison_set']['n']:,} physicists and chemists matched to OpenAlex "
  f"({r1['comparison_set']['women']} women, {r1['comparison_set']['men']:,} men), inside a network of "
  f"{r1['graph']['nodes']:,} pages and {r1['graph']['edges']:,} links.\n")
A("**Raw numbers (not adjusted, for orientation only)**\n")
A("| | Women | Men |\n|---|---|---|")
for k, lab, pct in (("in_degree", "Links received (mean in-degree)", 0), ("out_degree", "Links given (mean out-degree)", 0),
                    ("reciprocal", "Reciprocal links (mean)", 0), ("zero_in", "No incoming link", 1),
                    ("zero_out", "No outgoing link", 1), ("isolate", "Isolate (no link in or out)", 1)):
    f = (lambda v: f"{v:.1%}") if pct else (lambda v: f"{v:.2f}")
    A(f"| {lab} | {f(D[k]['female'])} | {f(D[k]['male'])} |")
A("\n**Against the null** (gender shuffled within strata, network fixed, 1,000 shuffles). "
  "Ratio = women's observed value / value expected under shuffling.\n")
A("| Outcome | Field × decade × citation quintile | z | Subfield × decade × citation tercile | z |\n|---|---|---|---|---|")
for k, lab in (("in_degree", "Links received"), ("out_degree", "Links given"), ("reciprocal", "Reciprocal links"),
               ("zero_in", "Share with no incoming link"), ("isolate", "Share isolated")):
    A(f"| {lab} | {P[k]['ratio_obs_over_null']:.2f} | {P[k]['z']:+.1f} | {P2[k]['ratio_obs_over_null']:.2f} | {P2[k]['z']:+.1f} |")
A(f"\nThe subfield strata are fine-grained: only {P2['women_in_mixed_strata']} of {r1['comparison_set']['women']} women sit in a "
  f"stratum that also contains a man (against {P['women_in_mixed_strata']} for the coarser strata), so that test has less power. "
  f"The gap in links received and given holds; the share with no incoming link is no longer distinguishable from the null there "
  f"(z = {P2['zero_in']['z']:+.1f}).\n")
A("**Count models for links received** (female coefficient as a rate ratio; controls: log citations, field, birth decade, deceased)\n")
A("| Model | Women / men | 95% CI |\n|---|---|---|")
A(f"| Negative binomial (headline) | {nb['irr']:.2f} | {ci(nb['ci95'])} |")
A(f"| Poisson, robust SE | {M['poisson_robust']['irr']:.2f} | {ci(M['poisson_robust']['ci95'])} |")
A(f"| Poisson, SE clustered by link community | {r1['clustered_by_community']['irr']:.2f} | {ci(r1['clustered_by_community']['ci95'])} |")
A(f"| Hurdle, part 1: any incoming link (percentage points) | {H['any_link_diff_pct_points']:+.1f} | {ci(H['any_link_diff_ci95'], 1)} |")
A(f"| Hurdle, part 2: links, given at least one | {H['count_given_any_rate_ratio']:.2f} | {ci(H['count_given_any_ci95'])} |")
A(f"| Prose-only links, negative binomial | {r1['models_in_degree_prose']['negative_binomial']['irr']:.2f} | {ci(r1['models_in_degree_prose']['negative_binomial']['ci95'])} |")
A(f"| Links *given* (out-degree), negative binomial | {MO['negative_binomial']['irr']:.2f} | {ci(MO['negative_binomial']['ci95'])} |")
A(f"| Supplement: PageRank, log scale (old headline) | {r1['pagerank_supplement']['ratio_geometric']:.2f} | {ci(r1['pagerank_supplement']['ci95'])} |")
A(f"\nThe old headline (\"14% lower PageRank\") understated the gap. Almost half of the pages sit at the PageRank floor, "
  f"so a log-PageRank ratio compresses a {100 * (1 - nb['irr']):.0f}% gap in links into about "
  f"{100 * (1 - r1['pagerank_supplement']['ratio_geometric']):.0f}%.\n")
A("**What the gap runs through** (negative binomial, controls added one at a time)\n")
A("| Specification | Women / men | 95% CI |\n|---|---|---|")
for x in r1["ladder_in_degree_negbin"]:
    A(f"| {x['spec']} | {x['irr']:.2f} | {ci(x['ci95'])} |")
A("\nPage length does not account for the gap. The number of links on the page and the page's own links to scientists "
  "account for part of it. These are pathways, not confounders (linking is often mutual), so the honest reading is: "
  "women's pages are less woven into the network in both directions, and we cannot separate \"others link to them less\" "
  "from \"their pages link out less\".\n")
A("**Field × gender in one model** (physics, chemistry and biology on the full three-field network, "
  f"{F['graph_nodes']:,} pages, n = {F['n']:,})\n")
A("| Field | n (women) | Women / men | 95% CI |\n|---|---|---|---|")
for f in ("physics", "chemistry", "biology"):
    b = F["by_field"][f]
    A(f"| {f.capitalize()} | {b['n']:,} ({b['women']}) | {b['irr']:.2f} | {ci(b['ci95'])} |")
A(f"\nJoint test that the gap differs between fields: p = {F['joint_interaction_p']:.2f}. On the count scale biology is "
  f"**not** an exception; the earlier \"biology gap almost disappears\" came from the log-PageRank scale, where biology's "
  f"larger share of unlinked pages hides the difference. What is different in biology is page length: women's pages are "
  f"about {100 * (F['page_length_ratio_biology'] - 1):.0f}% longer there (ratio {F['page_length_ratio_physics']:.2f} in physics).\n")
A("**Robustness** (`results/rq1_robustness.csv`)\n")
rb = pd.DataFrame(r1["robustness"])
A("| Variant | n (women) | Links received: obs/expected (z) | NB rate ratio [95% CI] | Links given: obs/expected | Isolates: obs/expected |\n|---|---|---|---|---|---|")
for x in rb.itertuples():
    A(f"| {x.variant} | {x.n:,} ({x.women}) | {x.in_degree_ratio_perm:.2f} ({x.z:+.1f}) | {x.in_degree_irr_nb:.2f} [{x.irr_lo:.2f}, {x.irr_hi:.2f}] | {x.out_degree_ratio_perm:.2f} | {x.isolate_ratio_perm:.2f} |")

A("\n## Selection check\n")
A("Only pages with an ORCID or OpenAlex ID on Wikidata can be compared at equal citations. Match rates:\n")
A("| Birth decade | Women matched | Men matched |\n|---|---|---|")
for dec, v in s["match_rate_by_decade"].items():
    A(f"| {dec}s | {v['women']:.0%} of {v['n_women']} | {v['men']:.0%} of {v['n_men']} |")
sb = s["share_born_1970_or_later"]
A(f"\nBorn 1970 or later: {sb['matched_women']:.0%} of matched women and {sb['matched_men']:.0%} of matched men "
  f"(all pages: {sb['all_women']:.0%} and {sb['all_men']:.0%}).\n")
A("Gap in links received **without** a citation control (field, decade, deceased, page length, prizes), by match status:\n")
A("| Pages | n (women) | Raw mean in-degree, women / men | NB rate ratio | 95% CI |\n|---|---|---|---|---|")
for k, v in g.items():
    A(f"| {k} | {v['n']:,} ({v['women']}) | {v['raw_mean_in_degree']['female']:.2f} / {v['raw_mean_in_degree']['male']:.2f} | "
      f"{v['negbin_irr']['irr']:.2f} | {ci(v['negbin_irr']['ci95'])} |")
A(f"\nThe gap among the {g['not matched']['n']:,} unmatched pages is the same size as among matched pages, so it is not created "
  f"by the matching. Reweighting the comparison set to resemble all pages gives a rate ratio of "
  f"{s['ipw']['weighted_poisson']['irr']:.2f} {ci(s['ipw']['weighted_poisson']['ci95'])} "
  f"(unweighted Poisson {s['ipw']['unweighted_poisson']['irr']:.2f}). What this cannot show is whether the gap holds "
  f"*at equal citations* among unmatched people: that needs `r4b_openalex_namematch.py`, which is written but **not run** "
  f"(the OpenAlex API was not reachable from the machine used for the revision).\n")

A("## RQ3. Who links to women's pages\n")
A(f"{r3['women_to_women_edges']} of the {r3['edges_to_women']} links to women's pages come from women's pages "
  f"({r3['observed_share_from_women']:.1%}); women's pages are {r3['share_women_among_all_linking_pages']:.1%} of all linking pages.\n")
A("| Null (gender shuffled within…) | Expected share | z |\n|---|---|---|")
A(f"| field × decade (original) | {r3['null_field_x_decade']['null_mean']:.1%} | {r3['null_field_x_decade']['z']:+.1f} |")
for k, lab in (("community", "link community"), ("community_x_decade", "link community × decade (revised)"),
               ("community_x_decade_x_field", "link community × decade × field")):
    x = r3[f"summary_{k}"]
    A(f"| {lab}, 10 Louvain partitions | {x['null_mean_range'][0]:.1%} to {x['null_mean_range'][1]:.1%} | {x['z_range'][0]:+.1f} to {x['z_range'][1]:+.1f} |")
A(f"\nThe result does **not** disappear under the community × decade null: it gets stronger. The original null moved "
  f"gender labels onto pages regardless of whether they link at all, which overstated how many links from women to expect. "
  f"About {cx['share_women_in_mixed_cells_avg']:.0%} of linked women sit in a community × decade cell that also contains a man, "
  f"so the null has room to move. The \"to men\" z-score of the old analysis is the same fact seen from the other side and is not reported "
  f"as a second finding. The within-community PageRank percentile is dropped: it restated RQ1 without an impact control.\n")
lo, hi = r3["share_women_range_in_communities_ge100"]
A(f"Women are {lo:.1%} to {hi:.1%} of the {len(r3['communities_seed0_ge100'])} link communities with at least 100 pages "
  f"(one Louvain partition). They are present in every large community but unevenly; we do not claim they are spread evenly.\n")

A("## RQ2. How the pages are written\n")
A(f"**Classifier.** TF-IDF + logistic regression on the masked text, 5-fold cross-validated, {c['n_pages']:,} pages, {c['n_features']:,} words.\n")
A("| | Observed AUC | Shuffled-gender null (mean, 95% range) | z |\n|---|---|---|---|")
for k, lab in (("pooled_auc", "All pages pooled"), ("within_field_decade_auc", "Within field × birth decade")):
    x = c[k]
    A(f"| {lab} | {x['observed']:.3f} | {x['null_mean']:.3f} {ci(x['null_ci95'], 3)} | {x['z']:+.1f} |")
A(f"\nField, birth decade, citations, page length and deceased alone give AUC {r2['metadata_only_auc']:.2f}. "
  f"The pooled null sits at {c['pooled_auc']['null_mean']:.2f}, not 0.50, because a classifier can learn cohort and field from text; "
  f"the within-stratum AUC removes that and its null sits at {c['within_field_decade_auc']['null_mean']:.2f}. "
  f"Dropping a further list of leak words changed the within-stratum AUC from "
  f"{r2['classifier_original_masking']['within_field_decade_auc']['observed']:.3f} to {c['within_field_decade_auc']['observed']:.3f}.\n")
A("**What an AUC this high does and does not mean.** It shows the pages differ systematically. It does not show that the "
  "difference is in how women are *described*. The strongest women-side words include British spellings and house-style verbs "
  "(*whilst, honours, characterisation, considers, earned, completed*), which would fit pages written recently by a "
  "small number of editors with a consistent style. We could not test this (it needs each "
  "page's creator and creation date from the revision history). Treat authorship as a live alternative explanation.\n")
A("**Distinguishing words, within field × birth decade**\n")
A(f"- Women's pages: {', '.join(w['top_women_within_field_decade'][:18])}")
A(f"- Men's pages: {', '.join(w['top_men_within_field_decade'][:18])}\n")
A(f"Of the 60 strongest words from the unadjusted comparison, {w['pooled_top60_same_sign_within_decade']:.0%} keep their direction "
  f"inside birth decades and {w['pooled_top60_still_abs_z_above_1.96_within_decade']:.0%} stay beyond |z| = 1.96; the ones that do not: "
  f"{', '.join(w['pooled_top60_lost'])}. Words with |z| > 3: {w['n_words_abs_z_above_3_pooled']} unadjusted, "
  f"{w['n_words_abs_z_above_3_within_field_decade']} within field × decade (part of the drop is cohort, part is the smaller cells).\n")
sh = w["split_half"]
A(f"**Held-out check.** Words chosen on one random half of the pages point the same way in the other half "
  f"{sh['top60_same_sign_in_held_out_half_mean']:.0%} of the time (range {sh['top60_same_sign_range'][0]:.0%} to "
  f"{sh['top60_same_sign_range'][1]:.0%} over {sh['splits']} splits; chance is 50%), and "
  f"{sh['top60_same_sign_and_abs_z_above_1.96_mean']:.0%} are also beyond |z| = 1.96 in the held-out half. Direction replicates; "
  f"individual words should not be over-read.\n")
e = r2["explicit_gender_mentions"]
A(f"**Explicit gender mentions** (\"first woman to\", \"female physicist\"; unmasked text): {e['share_women']:.1%} of women's pages, "
  f"{e['share_men']:.1%} of men's; adjusted difference {e['adjusted_diff_pct_points']:.1f} points {ci(e['ci95'], 1)}.\n")
A("**Dropped.** The personal-life word list (it found 51% of personal sentences on women's pages but 33% on men's, so it cannot "
  "compare genders), and with it the 4.9% vs 2.8% difference in the top citation quintile, which stays an untested lead.\n")

A("## What is still open\n")
A("1. **Human validation.** `validation/` holds blind sheets for two people (100 matches, 300 sentences). Until they are filled in, "
  "the only labels are AI-assisted, and the paper must say so. 50 of 50 correct per gender has a 95% interval of 93% to 100%: "
  "it cannot rule out a difference in match quality between women and men.")
A("2. **Selection at equal citations.** Run `r4b_openalex_namematch.py` with the OpenAlex key.")
A("3. **Page age and authorship.** Creation date and creator per page (one revisions API call each) would test the two main "
  "alternative explanations: women's pages are newer, and they are written by fewer editors.")
A("4. **h-index** comes from the largest OpenAlex profile while citations are summed over split profiles; the single-profile "
  "row in the robustness table avoids the mismatch and gives the same answer.")
(ROOT / "CONCLUSIONS.md").write_text("\n".join(L) + "\n")
print("wrote CONCLUSIONS.md", len(L), "lines")
